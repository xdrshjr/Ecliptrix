"""D2 fixture media — a synthetic, self-describing test pattern.

Why synthetic rather than a clip out of ``static/uploads``:

* **Deterministic.** The plan's D2 records real material by path + SHA256, but
  those files are not in version control, so a result nobody can reproduce is
  worth little. This pattern is regenerated byte-identically from code.
* **Static in time.** The preview capture seeks a ``<video>`` element while the
  export walks frame indices; a pattern whose content changes over time would
  fold seek precision into every M2 number. Holding the content constant leaves
  the camera move as the only thing that differs between two frames.
* **Diagnostic.** Corner glyphs differ by shape AND colour, so the raster-order
  corner transposition (L12) shows up as an obviously wrong picture rather than
  a slightly-off SSIM. Dense text and grid lines give SSIM something to bite on;
  a smooth gradient would score high even when badly misaligned.

Nothing here is imported by production code.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Tuple

from PIL import Image, ImageDraw, ImageFont

import _common as C

_FONT_CANDIDATES = (
    "C:/Windows/Fonts/arialbd.ttf",
    "C:/Windows/Fonts/arial.ttf",
    "C:/Windows/Fonts/segoeui.ttf",
)


def _font(size: int) -> ImageFont.ImageFont:
    for candidate in _FONT_CANDIDATES:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default()


def _draw_corner_glyphs(draw: ImageDraw.ImageDraw, width: int, height: int) -> None:
    """Four corner marks that are distinguishable under any flip or rotation."""
    inset = int(min(width, height) * 0.045)
    box = int(min(width, height) * 0.09)
    label_font = _font(max(18, box // 3))

    # Top-left: filled square, red.
    draw.rectangle([inset, inset, inset + box, inset + box], fill=(228, 62, 62))
    draw.text((inset + 6, inset + box + 6), "TL", font=label_font, fill=(255, 255, 255))

    # Top-right: circle, green.
    draw.ellipse(
        [width - inset - box, inset, width - inset, inset + box], fill=(64, 190, 106)
    )
    draw.text(
        (width - inset - box, inset + box + 6), "TR", font=label_font, fill=(255, 255, 255)
    )

    # Bottom-right: triangle, blue.
    draw.polygon(
        [
            (width - inset - box, height - inset),
            (width - inset, height - inset),
            (width - inset - box // 2, height - inset - box),
        ],
        fill=(74, 132, 240),
    )
    draw.text(
        (width - inset - box, height - inset - box - 40),
        "BR",
        font=label_font,
        fill=(255, 255, 255),
    )

    # Bottom-left: diamond, amber.
    cx, cy = inset + box // 2, height - inset - box // 2
    draw.polygon(
        [(cx, cy - box // 2), (cx + box // 2, cy), (cx, cy + box // 2), (cx - box // 2, cy)],
        fill=(244, 186, 66),
    )
    draw.text((inset, cy - box), "BL", font=label_font, fill=(255, 255, 255))


def build_pattern(width: int, height: int, out_png: Path) -> Path:
    """Render the test pattern at ``width`` x ``height``."""
    image = Image.new("RGB", (width, height))
    pixels = image.load()
    # Background gradient — low frequency, so it never dominates SSIM.
    for y in range(height):
        for x in range(0, width, 4):
            r = 18 + int(70 * x / width)
            g = 20 + int(40 * y / height)
            b = 46 + int(90 * (1 - x / width))
            for dx in range(4):
                if x + dx < width:
                    pixels[x + dx, y] = (r, g, b)

    draw = ImageDraw.Draw(image)
    cols, rows = 16, 9
    cell_w, cell_h = width / cols, height / rows
    cell_font = _font(max(14, int(cell_h * 0.18)))
    for row in range(rows):
        for col in range(cols):
            x0, y0 = col * cell_w, row * cell_h
            if (row + col) % 2 == 0:
                draw.rectangle([x0, y0, x0 + cell_w, y0 + cell_h], fill=(52, 58, 84))
            draw.rectangle(
                [x0, y0, x0 + cell_w, y0 + cell_h], outline=(150, 158, 186), width=2
            )
            draw.text(
                (x0 + 10, y0 + 8), f"{chr(65 + col)}{row + 1}", font=cell_font, fill=(228, 232, 245)
            )

    # Concentric rings + a diagonal: high-frequency, rotation-sensitive content
    # placed off-centre so a mirrored render cannot coincidentally match.
    cx, cy = width * 0.42, height * 0.46
    for radius in range(40, int(min(width, height) * 0.42), 34):
        draw.ellipse([cx - radius, cy - radius, cx + radius, cy + radius], outline=(255, 255, 255), width=3)
    draw.line([(0, height), (width, 0)], fill=(255, 120, 200), width=5)

    title_font = _font(int(height * 0.06))
    draw.text((width * 0.30, height * 0.86), "CAMERA MOTION FIXTURE", font=title_font, fill=(255, 255, 255))
    _draw_corner_glyphs(draw, width, height)

    out_png.parent.mkdir(parents=True, exist_ok=True)
    image.save(out_png)
    return out_png


def encode_clip(png: Path, out_mp4: Path, duration: float, fps: int) -> Path:
    """Encode the still pattern into a normalized-looking clip.

    The result stands in for what ``_compose_videos_filtergraph`` actually
    receives: already trimmed, already scaled to the canvas, constant frame rate,
    yuv420p. CRF 12 keeps compression artefacts well below the SSIM signal.
    """
    out_mp4.parent.mkdir(parents=True, exist_ok=True)
    result = C.run(
        [
            C.FFMPEG,
            "-y",
            "-loop",
            "1",
            "-framerate",
            str(fps),
            "-i",
            str(png),
            "-t",
            f"{duration}",
            "-c:v",
            "libx264",
            "-preset",
            "medium",
            "-crf",
            "12",
            "-pix_fmt",
            "yuv420p",
            "-r",
            str(fps),
            str(out_mp4),
        ],
        timeout=600,
    )
    if not result.ok:
        raise RuntimeError(f"pattern encode failed: {result.stderr[-800:]}")
    return out_mp4


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ensure_fixture(width: int = C.CANVAS_WIDTH, height: int = C.CANVAS_HEIGHT) -> Tuple[Path, Path]:
    """Build (or reuse) the pattern PNG + clip for this canvas size."""
    work = C.work_dir()
    png = work / f"pattern_{width}x{height}.png"
    mp4 = work / f"pattern_{width}x{height}.mp4"
    if not png.exists():
        build_pattern(width, height, png)
    if not mp4.exists():
        encode_clip(png, mp4, C.CLIP_DURATION, C.FPS)
    return png, mp4


if __name__ == "__main__":
    png_path, mp4_path = ensure_fixture()
    print(f"{png_path} sha256={sha256(png_path)}")
    print(f"{mp4_path} sha256={sha256(mp4_path)}")
