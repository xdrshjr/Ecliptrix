const DICTIONARIES: Record<Locale, Dictionary> = { 'zh-CN': zhCN, 'en-US': enUS }

/** Translate a key, falling back to zh-CN and then to the key itself. */
export function t(key: string, locale: Locale = DEFAULT_LOCALE, vars?: Record<string, string | number>): string {
  const dictionary = DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE]
  const template = dictionary[key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}

/** Translator bound to a locale — the shape every server component receives. */
export type Translator = (key: string, vars?: Record<string, string | number>) => string

export function translator(locale: Locale): Translator {
  return (key, vars) => t(key, locale, vars)
}

export function isLocale(value: string | undefined | null): value is Locale {
  return Boolean(value) && (LOCALES as readonly string[]).includes(value as string)
}

/** Error code → user-facing copy, with a safe generic fallback. */
export function errorMessage(code: string, locale: Locale = DEFAULT_LOCALE): string {
  return t(`errors.${code}`, locale, undefined) === `errors.${code}`
    ? t('errors.generic', locale)
    : t(`errors.${code}`, locale)
}

