def _zoompan_z(chain: str) -> str:
    return chain.split("zoompan=z='", 1)[1].split("'", 1)[0]


class TestPiecewiseStructure:
    def test_four_keyframes_give_two_nested_ifs(self):
        m = motion(stops=[
            {"at": 0.0, "scale": 1.0, "easing": "linear"},
            {"at": 0.3, "scale": 1.6, "easing": "linear"},
            {"at": 0.7, "scale": 1.2, "easing": "linear"},
            {"at": 1.0, "scale": 1.4},
        ])
        chain, warnings = build(m)
        assert warnings == []
        # n stops -> n-1 segments -> n-2 nested `if`s; the last segment is bare.
        assert _zoompan_z(chain).count("if(lt(") == 2

