def motion(mode="2d", intensity=1.0, easing="easeInOut", stops=None, **overrides):
    """A wire-shaped motion dict, with an optional curve."""
    payload = {
        "version": 1,
        "mode": mode,
        "preset_id": "custom",
        "intensity": intensity,
        "easing": easing,
        "start": dict(DEFAULT),
        "end": dict(DEFAULT),
    }
    if stops is not None:
        full = [{**DEFAULT, **stop} for stop in stops]
        payload["keyframes"] = full
        payload["start"] = {key: full[0][key] for key in DEFAULT}
        payload["end"] = {key: full[-1][key] for key in DEFAULT}
    payload.update(overrides)
    return payload


def preset_motion(entry):
    preset_id, mode, start, end = entry
    return {
        "version": 1, "mode": mode, "preset_id": preset_id, "intensity": 1.0,
        "easing": "easeInOut",
        "start": {**DEFAULT, **start}, "end": {**DEFAULT, **end},
    }


def build(m, **kwargs):
    kwargs.setdefault("caps", CAPS)
    kwargs.setdefault("config", CONFIG)
    kwargs.setdefault("label", "clip")
    return build_camera_filter_chain(m, FRAME_W, FRAME_H, FPS, CLIP, **kwargs)


