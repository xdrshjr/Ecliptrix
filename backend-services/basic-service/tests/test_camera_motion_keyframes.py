def _long_curve():
    """Eight keyframes moving every 2D component — the longest legal chain."""
    stops = []
    for i in range(CAMERA_MAX_KEYFRAMES):
        stops.append({
            "at": i / (CAMERA_MAX_KEYFRAMES - 1),
            "scale": 1.0 + 0.31 * (i % 3),
            "x": 0.5 + 0.13 * math.sin(i),
            "y": 0.5 + 0.11 * math.cos(i),
            "roll": 7.0 * math.sin(i * 1.7),
            "easing": ("linear", "easeIn", "easeOut", "easeInOut")[i % 4],
        })
    return motion(stops=stops)


class TestLengthGate:
    def test_a_normal_eight_keyframe_curve_is_well_under_the_ceiling(self):
        chain, warnings = build(_long_curve())
        assert len(chain) < CONFIG.max_expr_chars
        assert not any("too complex" in w for w in warnings)

    def test_over_the_ceiling_it_collapses_to_the_two_point_chain(self):
        tight = CameraMotionConfig(max_expr_chars=400)
        m = _long_curve()
        chain, warnings = build(m, config=tight)
        plain = dict(m)
        plain.pop("keyframes")
        expected, _ = build(plain, config=tight)
        assert chain == expected
        assert any("two-keyframe motion" in w for w in warnings), warnings

    def test_it_degrades_exactly_one_level(self):
        """`allow_collapse=False` on the recursive call; no second notice."""
        tight = CameraMotionConfig(max_expr_chars=1)
        _chain, warnings = build(_long_curve(), config=tight)
        assert sum("two-keyframe motion" in w for w in warnings) == 1

    def test_the_collapsed_chain_is_returned_even_if_still_too_long(self):
        """P2-4: never return '' — that is one more silent way to lose a motion."""
