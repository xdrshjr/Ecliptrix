class TestStringZeroRegression:
    @pytest.mark.parametrize("entry", PRESETS, ids=[p[0] for p in PRESETS])
    def test_every_preset_matches_its_pre_curve_baseline(self, entry):
        chain, warnings = build(preset_motion(entry))
        assert warnings == []
        assert chain == CAMERA_CHAIN_BASELINES[entry[0]]

    def test_a_two_stop_curve_is_the_same_string_as_no_curve(self):
        """D38's data-level twin: a trivial curve must not change the output.

        The frontend deletes such a curve before it is ever sent, but a
        hand-edited project file could still carry one, and it must not render
        differently from the identical two-point motion.
        """
        plain = preset_motion(PRESETS[0])
        trivial = dict(plain)
        trivial["keyframes"] = [
            {**plain["start"], "at": 0.0, "easing": "easeInOut"},
            {**plain["end"], "at": 1.0, "easing": None},
        ]
        assert build(trivial)[0] == build(plain)[0]

    def test_identity_motion_still_yields_an_empty_chain(self):
        chain, warnings = build(motion())
        assert chain == ""
        assert warnings == []


