"""
Shared grid pack service — centralizes the prompt construction, cell cropping
and filesystem layout used by storyboard / character / scene "grid packs".

A "grid pack" is a single square image generated by ARK Seedream that has
been partitioned into a rows x cols grid, with each cell cropped to an
individual frame PNG on disk and a metadata.json descriptor. The three
concrete pack types share the same on-disk structure — only the prompt and
the list of sub-view labels differ:

    {storage_root}/{storage_dir}/{YYYYMMDD}/{pack_id}/
        original.png
        frame_001.png ... frame_NNN.png
        metadata.json
        (optional) reference.png

Historically this logic lived inside ``storyboard_service``; it has been
extracted so that character and scene modeling can reuse the exact same
pipeline. ``storyboard_service`` now delegates prompt building and cropping
to this module.
"""

