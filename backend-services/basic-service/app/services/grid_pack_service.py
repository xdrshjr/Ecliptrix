async def write_pack_metadata(pack_dir: str, metadata: dict) -> str:
    """Write metadata.json for a pack and return the path."""
    metadata.setdefault("created_at", datetime.now(timezone.utc).isoformat())
    metadata_path = os.path.join(pack_dir, "metadata.json")
    async with aiofiles.open(metadata_path, "w", encoding="utf-8") as f:
        await f.write(json.dumps(metadata, ensure_ascii=False, indent=2))
    return metadata_path


# ---------------------------------------------------------------------------
# Reference-image normalization (R1)
# ---------------------------------------------------------------------------

# Recognized "local" URL prefixes — resolved to disk reads and inlined as data
# URIs so that ARK (which cannot reach private /api paths) accepts them.
_LOCAL_URL_PREFIXES = ("/api/storage/files/",)


def _guess_mime(path: str) -> str:
    lower = path.lower()
    if lower.endswith(".png"):
        return "image/png"
    if lower.endswith(".jpg") or lower.endswith(".jpeg"):
        return "image/jpeg"
    if lower.endswith(".webp"):
        return "image/webp"
    if lower.endswith(".gif"):
        return "image/gif"
    return "image/png"


async def _read_as_data_uri(abs_path: str) -> str:
    async with aiofiles.open(abs_path, "rb") as f:
        data = await f.read()
    mime = _guess_mime(abs_path)
    b64 = base64.b64encode(data).decode("ascii")
    return f"data:{mime};base64,{b64}"


async def resolve_reference_to_base64_or_url(value: Optional[str]) -> Optional[str]:
    """Normalize a reference image value to something ARK can consume.

    Rules (R1):
      * ``None`` / empty → ``None`` (caller treats as "no reference").
      * ``data:`` URI → returned unchanged.
      * ``http(s)://`` URL → returned unchanged (ARK can fetch it).
      * ``/api/storage/files/...`` local serving URL → read the underlying
        file from ``storage_root()`` and return a base64 data URI.
      * Absolute/relative filesystem path that points into the storage root
        → read and inline as base64 data URI.
      * Anything else → raise ``ValueError`` (let the caller surface 400).
    """
    if not value:
        return None

    if value.startswith("data:") or value.startswith("http://") or value.startswith("https://"):
        return value

    # Always resolve to an absolute, normalized path so commonpath does not
    # raise ValueError when the configured STORAGE_ROOT is relative (the
    # default is "static/uploads") and the candidate has been absolutized
    # from cwd. Mixing absolute + relative inputs into commonpath blew up
    # silently and caused chain references to fail downstream.
    root = os.path.abspath(storage_root())

    def _is_within_root(abs_path: str) -> bool:
        try:
            a = os.path.abspath(abs_path)
            common = os.path.normcase(os.path.commonpath([a, root]))
            return common == os.path.normcase(root)
        except ValueError:
            # Different drives / roots — not "inside" root, but log so
            # future regressions are not silently swallowed.
            logger.debug(
                "_is_within_root: commonpath ValueError for path=%r root=%r",
                abs_path,
                root,
            )
            return False

    # Case: public serving URL → map to filesystem.
    for prefix in _LOCAL_URL_PREFIXES:
        if value.startswith(prefix):
            relative = value[len(prefix):]
            if ".." in relative.split("/"):
                raise ValueError(f"Invalid reference image path (traversal): {value}")
            abs_path = os.path.normpath(os.path.join(root, relative))
            if not _is_within_root(abs_path):
                raise ValueError(f"Reference image path escapes storage root: {value}")
            if not os.path.isfile(abs_path):
                raise ValueError(f"Reference image file not found: {value}")
            return await _read_as_data_uri(abs_path)

    # Case: filesystem path. Accept absolute paths that live under the
    # storage root, plus relative paths resolved from cwd if they exist.
    candidate = value
    if not os.path.isabs(candidate):
        candidate = os.path.normpath(os.path.join(os.getcwd(), candidate))
    candidate = os.path.normpath(candidate)
    if os.path.isfile(candidate) and _is_within_root(candidate):
        return await _read_as_data_uri(candidate)

    raise ValueError(f"Unsupported reference image value: {value!r}")


