async def read_pack_metadata(pack_type: str, pack_id: str) -> dict:
    """Load the raw metadata.json for a pack, raising FileNotFoundError if missing."""
    validate_pack_id(pack_id)
    pack_dir = locate_pack_dir(pack_type, pack_id)
    if not pack_dir:
        raise FileNotFoundError(f"{pack_type} pack not found: {pack_id}")
    meta_path = os.path.join(pack_dir, "metadata.json")
    if not os.path.isfile(meta_path):
        raise FileNotFoundError(f"metadata.json missing for pack: {pack_id}")
    async with aiofiles.open(meta_path, "r", encoding="utf-8") as f:
        return json.loads(await f.read())


def _pack_dict_from_metadata(pack_type: str, date_str: str, meta: dict) -> dict:
    """Enrich raw metadata with resolved URLs for the response payload.

    The ``file_ext`` field on metadata.json (introduced for frame packs) tells
    us which extension the generic ``original.<ext>`` fallback should use.
    Older storyboard / character / scene packs have no ``file_ext`` and
    continue to default to ``"png"``.
    """
    pack_id = meta["pack_id"]
    file_ext = meta.get("file_ext", "png")
    frames = []
    for fr in meta.get("frames", []):
        frames.append({
            "index": fr["index"],
            "filename": fr["filename"],
            "url": frame_url(pack_type, date_str, pack_id, fr["filename"]),
            "row": fr.get("row", 0),
            "col": fr.get("col", 0),
            "sub_view": fr.get("sub_view"),
            "description": fr.get("description"),
            "timestamp_sec": fr.get("timestamp_sec"),
            "width": fr.get("width"),
            "height": fr.get("height"),
        })

    return {
        "pack_id": pack_id,
        "pack_type": meta.get("pack_type", pack_type),
        "prompt": meta.get("prompt", ""),
        "grid_size": meta.get("grid_size", "3x3"),
        "aspect_ratio": meta.get("aspect_ratio", "1:1"),
        "frame_count": meta.get("frame_count", len(frames)),
        "sub_views": meta.get("sub_views", []),
        "created_at": meta.get("created_at", ""),
        "original_image_url": meta.get(
            "original_image_url",
            frame_url(pack_type, date_str, pack_id, f"original.{file_ext}"),
        ),
        "reference_image_url": meta.get("reference_image"),
        "frames": frames,
        "source_material_id": meta.get("source_material_id"),
        "source_material_name": meta.get("source_material_name"),
        "source_duration_sec": meta.get("source_duration_sec"),
    }


async def list_packs(pack_type: str) -> List[dict]:
    """Scan the pack type's base directory and return packs newest first."""
    base = pack_base_dir(pack_type)
    packs: List[dict] = []
    if not os.path.isdir(base):
        return packs
    for date_dir_name in sorted(os.listdir(base), reverse=True):
        date_dir = os.path.join(base, date_dir_name)
        if not os.path.isdir(date_dir):
            continue
        for pack_id in os.listdir(date_dir):
            pack_path = os.path.join(date_dir, pack_id)
            meta_path = os.path.join(pack_path, "metadata.json")
            if not os.path.isfile(meta_path):
                continue
            try:
                async with aiofiles.open(meta_path, "r", encoding="utf-8") as f:
                    meta = json.loads(await f.read())
                packs.append(_pack_dict_from_metadata(pack_type, date_dir_name, meta))
            except Exception as exc:
                logger.warning(f"Failed to read {pack_type} pack at {pack_path}: {exc}")
    packs.sort(key=lambda p: p.get("created_at", ""), reverse=True)
    return packs


async def get_pack(pack_type: str, pack_id: str) -> dict:
    """Load a single pack, return the enriched dict."""
    validate_pack_id(pack_id)
    pack_dir = locate_pack_dir(pack_type, pack_id)
    if not pack_dir:
        raise FileNotFoundError(f"{pack_type} pack not found: {pack_id}")
    # Derive date_str from directory layout: .../{pack_type_dir}/{date}/{pack_id}
    date_str = os.path.basename(os.path.dirname(pack_dir))
    meta = await read_pack_metadata(pack_type, pack_id)
    return _pack_dict_from_metadata(pack_type, date_str, meta)


async def delete_pack(pack_type: str, pack_id: str) -> None:
    """Delete the pack directory from local disk (and OSS if configured)."""
    import shutil

    validate_pack_id(pack_id)
    pack_dir = locate_pack_dir(pack_type, pack_id)
    if not pack_dir:
        raise FileNotFoundError(f"{pack_type} pack not found: {pack_id}")

    date_str = os.path.basename(os.path.dirname(pack_dir))
    shutil.rmtree(pack_dir, ignore_errors=True)
    logger.info(f"Deleted {pack_type} pack directory: {pack_dir}")

    try:
        from app.services.oss_client import get_oss_client

        oss_client = get_oss_client()
        if oss_client:
            import asyncio
            prefix = f"{storage_dir_for(pack_type)}/{date_str}/{pack_id}/"

            def _delete():
                try:
                    import oss2
                    for obj in oss2.ObjectIterator(
                        oss_client.bucket,
                        prefix=oss_client.cfg.key_prefix + prefix,
                    ):
                        oss_client.bucket.delete_object(obj.key)
                except Exception as exc:
                    logger.warning(f"OSS prefix deletion error: {exc}")

            await asyncio.to_thread(_delete)
            logger.info(f"Deleted OSS objects for {pack_type} pack {pack_id}")
    except Exception as exc:
        logger.warning(f"OSS cleanup failed for {pack_type} pack {pack_id}: {exc}")


async def download_to(path: str, url: str, timeout: float = 60.0) -> None:
    """Download ``url`` to local ``path``. Follows redirects."""
    async with httpx.AsyncClient(timeout=timeout, follow_redirects=True) as client:
        resp = await client.get(url)
        resp.raise_for_status()
        async with aiofiles.open(path, "wb") as f:
            await f.write(resp.content)
