logger = get_logger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Shared with storyboard_service: pack directory names under storage_root.
STORYBOARD_STORAGE_DIR = "storyboard"
CHARACTER_STORAGE_DIR = "character_pack"
SCENE_STORAGE_DIR = "scene_pack"
FRAME_STORAGE_DIR = "frame_pack"

PACK_TYPE_STORYBOARD = "storyboard"
PACK_TYPE_CHARACTER = "character"
PACK_TYPE_SCENE = "scene"
PACK_TYPE_FRAME = "frame"

PackType = Literal["storyboard", "character", "scene", "frame"]

# Per-edge padding in pixels discarded when cropping each cell. Matches the
# storyboard value; white separator lines are ~2-3 px wide so 4 px is safe.
GRID_CROP_PADDING = 4

ASPECT_RATIOS: Dict[str, Tuple[int, int]] = {
    "1:1": (1, 1),
    "16:9": (16, 9),
    "9:16": (9, 16),
    "4:3": (4, 3),
    "3:4": (3, 4),
}

# R2 — fixed 9-view lists for character/scene grids. Index 0..8 maps to
# row-major position inside the 3x3 grid.
CHARACTER_SUB_VIEWS: List[str] = [
    "front",
    "3-quarter-left",
    "side-left",
    "back",
    "side-right",
    "3-quarter-right",
    "face-close-up",
    "upper-body",
    "full-body-action",
]

SCENE_SUB_VIEWS: List[str] = [
    "wide-panorama",
    "establishing-shot",
    "medium-shot",
    "close-up-detail",
    "top-down",
    "low-angle",
    "golden-hour-lighting",
    "night-lighting",
    "silhouette",
]


_SAFE_ID_PATTERN = re.compile(r"^[a-zA-Z0-9_-]+$")


def validate_pack_id(pack_id: str) -> None:
    """Raise ValueError if pack_id is unsafe for filesystem paths."""
    if not pack_id or not _SAFE_ID_PATTERN.match(pack_id):
        raise ValueError(f"Invalid pack_id: {pack_id!r}")


# ---------------------------------------------------------------------------
# Layout helpers
# ---------------------------------------------------------------------------

def storage_root() -> str:
    return settings.storage.root


def storage_dir_for(pack_type: str) -> str:
    if pack_type == PACK_TYPE_STORYBOARD:
        return STORYBOARD_STORAGE_DIR
    if pack_type == PACK_TYPE_CHARACTER:
        return CHARACTER_STORAGE_DIR
    if pack_type == PACK_TYPE_SCENE:
        return SCENE_STORAGE_DIR
    if pack_type == PACK_TYPE_FRAME:
        return FRAME_STORAGE_DIR
    raise ValueError(f"Unknown pack_type: {pack_type!r}")


def pack_base_dir(pack_type: str) -> str:
    return os.path.join(storage_root(), storage_dir_for(pack_type))


def locate_pack_dir(pack_type: str, pack_id: str) -> Optional[str]:
    """Scan date dirs under the pack type's base and return the pack path."""
    validate_pack_id(pack_id)
    base = pack_base_dir(pack_type)
    if not os.path.isdir(base):
        return None
    for date_dir in sorted(os.listdir(base), reverse=True):
        candidate = os.path.join(base, date_dir, pack_id)
        if os.path.isdir(candidate):
            return candidate
    return None


def frame_url(pack_type: str, date_str: str, pack_id: str, filename: str) -> str:
    """Build a serving URL for a frame inside a given pack."""
    return f"/api/storage/files/{storage_dir_for(pack_type)}/{date_str}/{pack_id}/{filename}"


def parse_grid_size(grid_size: str) -> Tuple[int, int]:
    parts = grid_size.split("x")
    return int(parts[0]), int(parts[1])


# ---------------------------------------------------------------------------
# Prompt construction
# ---------------------------------------------------------------------------

_RATIO_ORIENTATION_HINT = {
    "1:1": "square",
    "16:9": "横屏/landscape",
    "9:16": "竖屏/portrait",
    "4:3": "横屏/landscape",
    "3:4": "竖屏/portrait",
}


def build_grid_prompt(
    user_prompt: str,
    rows: int,
    cols: int,
    aspect_ratio: str = "1:1",
    sub_views: Optional[List[str]] = None,
    style_hint: Optional[str] = None,
) -> str:
    """Build the system prompt instructing Seedream to generate a rows x cols grid.

    Args:
        user_prompt: user-facing content description (subject of the pack).
        rows/cols:   grid dimensions.
        aspect_ratio: per-cell target aspect ratio (affects cell composition
                     hint; actual post-crop is handled by ``crop_grid``).
        sub_views:   optional list of view labels ordered row-major. When
                     provided, each cell is tagged with its corresponding
                     label in the prompt; used by character/scene packs.
        style_hint:  optional extra guidance prepended to the CONTENT block
                     (e.g. "consistent character design across all views").
    """
    ratio_instruction = ""
    if aspect_ratio != "1:1" and aspect_ratio in ASPECT_RATIOS:
        w, h = ASPECT_RATIOS[aspect_ratio]
        orientation = _RATIO_ORIENTATION_HINT.get(aspect_ratio, "square")
        ratio_instruction = (
            f"- Each cell's content should be composed for a {aspect_ratio} "
            f"({orientation}) viewing format, with subjects and key elements "
            "centered accordingly\n"
        )

    sub_view_block = ""
    if sub_views:
        lines = []
        for i, label in enumerate(sub_views[: rows * cols]):
            r = i // cols
            c = i % cols
            lines.append(f"  - cell[row={r}, col={c}]: {label}")
        sub_view_block = (
            "SUB-VIEW ASSIGNMENTS (row-major order):\n"
            + "\n".join(lines)
            + "\n\n"
        )

    style_block = f"STYLE: {style_hint}\n\n" if style_hint else ""

    return (
        f"Create a {rows}x{cols} grid reference sheet image.\n\n"
        "LAYOUT REQUIREMENTS:\n"
        f"- The image must be divided into exactly {rows} rows and {cols} columns\n"
        "- Each cell must be exactly the same size\n"
        "- There must be thin white separator lines (about 2-3 pixels wide) between each cell\n"
        "- The cells must fill the entire image with no margins\n"
        f"{ratio_instruction}\n"
        "STRICT VISUAL-ONLY REQUIREMENTS:\n"
        "- Each cell must contain ONLY visual imagery — absolutely NO text, subtitles, captions, watermarks, or any written characters\n"
        "- Do NOT include any numbers, numerical labels, or index annotations in any cell\n"
        "- Every cell must be pure visual content with no overlaid text or symbols of any kind\n\n"
        f"{sub_view_block}"
        f"{style_block}"
        "CONTENT:\n"
        f"{user_prompt}\n\n"
        "Each cell should contain a distinct view/frame as described above.\n"
        "The overall style must be perfectly consistent across all cells.\n"
    )


def build_character_grid_prompt(user_prompt: str, aspect_ratio: str = "1:1") -> str:
    """Character modeling prompt — 3x3 turnaround sheet with fixed sub-views."""
    return build_grid_prompt(
        user_prompt=(
            f"Character reference sheet of: {user_prompt}. "
            "Professional character turnaround — clean neutral background."
        ),
        rows=3,
        cols=3,
        aspect_ratio=aspect_ratio,
        sub_views=CHARACTER_SUB_VIEWS,
        style_hint=(
            "Identical character identity, outfit and proportions in every cell; "
            "consistent lighting and clean background; no text, no numbers, "
            "no framing lines inside cells."
        ),
    )


def build_scene_grid_prompt(user_prompt: str, aspect_ratio: str = "1:1") -> str:
    """Scene modeling prompt — 3x3 environment sheet with fixed sub-views."""
    return build_grid_prompt(
        user_prompt=(
            f"Scene / environment reference sheet of: {user_prompt}. "
            "Professional environment concept art sheet."
        ),
        rows=3,
        cols=3,
        aspect_ratio=aspect_ratio,
        sub_views=SCENE_SUB_VIEWS,
        style_hint=(
            "Same location, same weather, same art direction in every cell; "
            "only the shot/angle/lighting varies per cell; no text, no numbers."
        ),
    )


# ---------------------------------------------------------------------------
# Cropping
# ---------------------------------------------------------------------------

def crop_cell_to_aspect_ratio(cell: Image.Image, aspect_ratio: str) -> Image.Image:
    """Center-crop a single cell to match the target aspect ratio.

    If aspect_ratio is ``1:1`` or unknown, the cell is returned unchanged.
    """
    if aspect_ratio == "1:1" or aspect_ratio not in ASPECT_RATIOS:
        return cell
    target_w, target_h = ASPECT_RATIOS[aspect_ratio]
    w, h = cell.size
    target_ratio = target_w / target_h
    current_ratio = w / h
    if current_ratio > target_ratio:
        new_w = int(h * target_ratio)
        left = (w - new_w) // 2
        return cell.crop((left, 0, left + new_w, h))
    if current_ratio < target_ratio:
        new_h = int(w / target_ratio)
        top = (h - new_h) // 2
        return cell.crop((0, top, w, top + new_h))
    return cell


def crop_grid(
    image_path: str,
    rows: int,
    cols: int,
    output_dir: str,
    aspect_ratio: str = "1:1",
) -> List[dict]:
    """Crop a grid image into individual frame PNGs.

    Returns a list of frame descriptors (without URL) suitable for metadata.
    """
    img = Image.open(image_path)
    width, height = img.size

    cell_width = width // cols
    cell_height = height // rows
    padding = GRID_CROP_PADDING

    frames: List[dict] = []
    index = 0
    for row in range(rows):
        for col in range(cols):
            left = col * cell_width + padding
            upper = row * cell_height + padding
            right = (col + 1) * cell_width - padding
            lower = (row + 1) * cell_height - padding

            cell = img.crop((left, upper, right, lower))
            cell = crop_cell_to_aspect_ratio(cell, aspect_ratio)
            filename = f"frame_{index + 1:03d}.png"
            cell.save(os.path.join(output_dir, filename))

            frames.append({
                "index": index,
                "filename": filename,
                "row": row,
                "col": col,
            })
            index += 1

    logger.info(f"Cropped grid into {len(frames)} frames at {output_dir}")
    return frames


